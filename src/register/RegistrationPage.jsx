import React, {
  useEffect, useMemo, useState,
} from 'react';
import { useDispatch, useSelector } from 'react-redux';

import { EdlyLogistrationInfo } from '@edly-io/edly-saas-widget';
import { getConfig } from '@edx/frontend-platform';
import { sendPageEvent, sendTrackEvent } from '@edx/frontend-platform/analytics';
import { useIntl } from '@edx/frontend-platform/i18n';
import { Form, Spinner, StatefulButton } from '@openedx/paragon';
import classNames from 'classnames';
import PropTypes from 'prop-types';
import { Helmet } from 'react-helmet';
import Skeleton from 'react-loading-skeleton';

import {
  InstitutionLogistration,
  PasswordField,
  RedirectLogistration,
  ThirdPartyAuthAlert,
} from '../common-components';
import ConfigurableRegistrationForm from './components/ConfigurableRegistrationForm';
import RegistrationFailure from './components/RegistrationFailure';
import { PasswordStrength, TermsFooter, TwoStepHeader } from './components/TwoStepParts';
import {
  backupRegistrationFormBegin,
  clearRegistrationBackendError,
  registerNewUser,
  setEmailSuggestionInStore,
  setUserPipelineDataLoaded,
} from './data/actions';
import {
  ACCOUNT_STEP_FIELDS,
  FORM_SUBMISSION_ERROR,
  PROFILE_STEP_ROWS,
  TPA_AUTHENTICATION_FAILURE,
  TWO_STEP_ACCOUNT_FIELDS,
} from './data/constants';
import { validateProfileFields } from './data/profileRules';
import getBackendValidations from './data/selectors';
import {
  isFormValid, prepareRegistrationPayload,
} from './data/utils';
import messages from './messages';
import { EmailField, NameField, UsernameField } from './RegistrationFields';
import { getThirdPartyAuthContext as getRegistrationDataFromBackend } from '../common-components/data/actions';
import EnterpriseSSO from '../common-components/EnterpriseSSO';
import ThirdPartyAuth from '../common-components/ThirdPartyAuth';
import {
  COMPLETE_STATE, PENDING_STATE, REGISTER_PAGE,
} from '../data/constants';
import {
  getAllPossibleQueryParams, getTpaHint, getTpaProvider, isHostAvailableInQueryParams, setCookie,
} from '../data/utils';

/**
 * Main Registration Page component
 */
const RegistrationPage = (props) => {
  const { formatMessage } = useIntl();
  const dispatch = useDispatch();

  const registrationEmbedded = isHostAvailableInQueryParams();
  const platformName = getConfig().SITE_NAME;
  const flags = {
    showConfigurableEdxFields: getConfig().SHOW_CONFIGURABLE_EDX_FIELDS,
    showConfigurableRegistrationFields: getConfig().ENABLE_DYNAMIC_REGISTRATION_FIELDS,
    showMarketingEmailOptInCheckbox: getConfig().MARKETING_EMAILS_OPT_IN,
    autoGeneratedUsernameEnabled: getConfig().ENABLE_AUTO_GENERATED_USERNAME,
    // Per-tenant (MFE_CONFIG): account details first, then a mandatory profile step.
    twoStepRegistration: !!getConfig().TPDCO_TWO_STEP_REGISTRATION,
  };
  const {
    handleInstitutionLogin,
    institutionLogin,
  } = props;

  const backedUpFormData = useSelector(state => state.register.registrationFormData);
  const registrationError = useSelector(state => state.register.registrationError);
  const registrationErrorCode = registrationError?.errorCode;
  const registrationResult = useSelector(state => state.register.registrationResult);
  const shouldBackupState = useSelector(state => state.register.shouldBackupState);
  const userPipelineDataLoaded = useSelector(state => state.register.userPipelineDataLoaded);
  const submitState = useSelector(state => state.register.submitState);

  const fieldDescriptions = useSelector(state => state.commonComponents.fieldDescriptions);
  const optionalFields = useSelector(state => state.commonComponents.optionalFields);
  const thirdPartyAuthApiStatus = useSelector(state => state.commonComponents.thirdPartyAuthApiStatus);
  const autoSubmitRegForm = useSelector(state => state.commonComponents.thirdPartyAuthContext.autoSubmitRegForm);
  const thirdPartyAuthErrorMessage = useSelector(state => state.commonComponents.thirdPartyAuthContext.errorMessage);
  const finishAuthUrl = useSelector(state => state.commonComponents.thirdPartyAuthContext.finishAuthUrl);
  const currentProvider = useSelector(state => state.commonComponents.thirdPartyAuthContext.currentProvider);
  const providers = useSelector(state => state.commonComponents.thirdPartyAuthContext.providers);
  const secondaryProviders = useSelector(state => state.commonComponents.thirdPartyAuthContext.secondaryProviders);
  const pipelineUserDetails = useSelector(state => state.commonComponents.thirdPartyAuthContext.pipelineUserDetails);

  const backendValidations = useSelector(getBackendValidations);
  const queryParams = useMemo(() => getAllPossibleQueryParams(), []);
  const tpaHint = useMemo(() => getTpaHint(), []);

  const edlyPrefilledEmail = useSelector(state => state.emailCheck?.prefilledEmail);
  const edlyContext = useSelector(state => state.emailCheck?.context);
  const isNewUser = edlyContext?.is_new_user;
  const [formFields, setFormFields] = useState({
    ...backedUpFormData.formFields,
    email: (isNewUser ? edlyPrefilledEmail : '') || backedUpFormData.formFields.email,
  });
  const [configurableFormFields, setConfigurableFormFields] = useState({ ...backedUpFormData.configurableFormFields });
  const [errors, setErrors] = useState({ ...backedUpFormData.errors });
  const [errorCode, setErrorCode] = useState({ type: '', count: 0 });
  const [step, setStep] = useState(1);
  const [formStartTime, setFormStartTime] = useState(null);
  // temporary error state for embedded experience because we don't want to show errors on blur
  const [temporaryErrors, setTemporaryErrors] = useState({ ...backedUpFormData.errors });

  const { cta, host } = queryParams;
  const twoStep = flags.twoStepRegistration;
  const onAccountStep = twoStep && step === 1;
  // Two-step registration: label above the input with Figma placeholders; nothing changes for other tenants.
  const twoStepProps = (field) => (twoStep
    ? { labelAbove: true, placeholder: formatMessage(messages[`register.step.${field}.placeholder`]) } : {});
  const buttonLabel = cta
    ? formatMessage(messages['create.account.cta.button'], { label: cta })
    : formatMessage(messages['create.account.for.free.button']);
  let submitLabel = buttonLabel;
  if (onAccountStep) {
    submitLabel = formatMessage(messages['register.step.continue.button']);
  } else if (twoStep) {
    submitLabel = formatMessage(messages['register.step.create.account.button']);
  }

  /**
   * Set the userPipelineDetails data in formFields for only first time
   */
  useEffect(() => {
    if (!userPipelineDataLoaded && thirdPartyAuthApiStatus === COMPLETE_STATE) {
      if (thirdPartyAuthErrorMessage) {
        setErrorCode(prevState => ({ type: TPA_AUTHENTICATION_FAILURE, count: prevState.count + 1 }));
      }
      if (pipelineUserDetails && Object.keys(pipelineUserDetails).length !== 0) {
        const { name = '', username = '', email = '' } = pipelineUserDetails;
        setFormFields(prevState => ({
          ...prevState, name, username, email,
        }));
        dispatch(setUserPipelineDataLoaded(true));
      }
    }
  }, [ // eslint-disable-line react-hooks/exhaustive-deps
    thirdPartyAuthApiStatus,
    thirdPartyAuthErrorMessage,
    pipelineUserDetails,
    userPipelineDataLoaded,
  ]);

  useEffect(() => {
    if (!formStartTime) {
      sendPageEvent('login_and_registration', 'register');
      const payload = { ...queryParams, is_register_page: true };
      if (tpaHint) {
        payload.tpa_hint = tpaHint;
      }
      dispatch(getRegistrationDataFromBackend(payload));
      setFormStartTime(Date.now());
    }
  }, [dispatch, formStartTime, queryParams, tpaHint]);

  /**
   * Backup the registration form in redux when register page is toggled.
   */
  useEffect(() => {
    if (shouldBackupState) {
      dispatch(backupRegistrationFormBegin({
        ...backedUpFormData,
        configurableFormFields: { ...configurableFormFields },
        formFields: { ...formFields },
        errors: { ...errors },
      }));
    }
  }, [shouldBackupState, configurableFormFields, formFields, errors, dispatch, backedUpFormData]);

  useEffect(() => {
    if (backendValidations) {
      if (registrationEmbedded) {
        setTemporaryErrors(prevErrors => ({ ...prevErrors, ...backendValidations }));
      } else {
        setErrors(prevErrors => ({ ...prevErrors, ...backendValidations }));
      }
    }
  }, [backendValidations, registrationEmbedded]);

  useEffect(() => {
    // Step 1's fields are unmounted on step 2: send the user back so the field error is visible.
    if (twoStep && step === 2 && backendValidations
      && TWO_STEP_ACCOUNT_FIELDS.some(name => backendValidations[name])) {
      setStep(1);
    }
  }, [backendValidations]); // eslint-disable-line react-hooks/exhaustive-deps

  useEffect(() => {
    if (registrationErrorCode) {
      setErrorCode(prevState => ({ type: registrationErrorCode, count: prevState.count + 1 }));
    }
  }, [registrationErrorCode]);

  useEffect(() => {
    if (registrationResult.success) {
      // This event is used by GTM
      sendTrackEvent('edx.bi.user.account.registered.client', {});

      // This is used by the "User Retention Rate Event" on GTM
      setCookie(getConfig().USER_RETENTION_COOKIE_NAME, true);
    }
  }, [registrationResult]);

  const handleOnChange = (event) => {
    const { name } = event.target;
    const value = event.target.type === 'checkbox' ? event.target.checked : event.target.value;
    if (registrationError[name]) {
      dispatch(clearRegistrationBackendError(name));
    }
    setErrors(prevErrors => ({ ...prevErrors, [name]: '' }));
    setFormFields(prevState => ({ ...prevState, [name]: value }));
  };

  const handleErrorChange = (fieldName, error) => {
    if (registrationEmbedded) {
      setTemporaryErrors(prevErrors => ({
        ...prevErrors,
        [fieldName]: error,
      }));
      if (error === '' && errors[fieldName] !== '') {
        setErrors(prevErrors => ({
          ...prevErrors,
          [fieldName]: error,
        }));
      }
    } else {
      setErrors(prevErrors => ({
        ...prevErrors,
        [fieldName]: error,
      }));
    }
  };

  const registerUser = () => {
    const totalRegistrationTime = (Date.now() - formStartTime) / 1000;
    let payload = { ...formFields };

    if (currentProvider) {
      delete payload.password;
      payload.social_auth_provider = currentProvider;
    }
    if (flags.autoGeneratedUsernameEnabled) {
      delete payload.username;
    }

    // Validating form data before submitting
    const { isValid: baseValid, fieldErrors, emailSuggestion } = isFormValid(
      payload,
      registrationEmbedded ? temporaryErrors : errors,
      configurableFormFields,
      fieldDescriptions,
      formatMessage,
    );
    let isValid = baseValid;
    if (twoStep && step === 2) {
      // Profile fields: same format/length/choice rules as the backend; required ones are checked above.
      const profileErrors = validateProfileFields(
        configurableFormFields, { ...fieldDescriptions, ...optionalFields.fields }, formatMessage,
      );
      Object.keys(profileErrors).forEach(name => {
        if (!fieldErrors[name]) { fieldErrors[name] = profileErrors[name]; }
      });
      isValid = !PROFILE_STEP_ROWS.flat().some(name => fieldErrors[name]) && baseValid;
      const firstInvalid = PROFILE_STEP_ROWS.flat().find(name => fieldErrors[name]);
      if (firstInvalid) {
        document.querySelector(`[name="${firstInvalid}"]`)?.focus();
      }
    }
    setErrors({ ...fieldErrors });
    dispatch(setEmailSuggestionInStore(emailSuggestion));

    // returning if not valid
    if (!isValid) {
      setErrorCode(prevState => ({ type: FORM_SUBMISSION_ERROR, count: prevState.count + 1 }));
      return;
    }

    // Preparing payload for submission
    payload = prepareRegistrationPayload(
      payload,
      configurableFormFields,
      flags.showMarketingEmailOptInCheckbox,
      totalRegistrationTime,
      queryParams);

    // making register call
    dispatch(registerNewUser(payload));
  };

  const goToProfileStep = () => {
    // Validate only the account fields; the profile fields are validated on final submit.
    const accountDescriptions = Object.fromEntries(
      Object.entries(fieldDescriptions).filter(([name]) => ACCOUNT_STEP_FIELDS.includes(name)),
    );
    const payload = { ...formFields };
    if (currentProvider) {
      delete payload.password;
    }
    if (flags.autoGeneratedUsernameEnabled) {
      delete payload.username;
    }
    const { isValid, fieldErrors, emailSuggestion } = isFormValid(
      payload,
      registrationEmbedded ? temporaryErrors : errors,
      configurableFormFields,
      accountDescriptions,
      formatMessage,
    );
    setErrors({ ...fieldErrors });
    dispatch(setEmailSuggestionInStore(emailSuggestion));
    if (isValid) {
      setStep(2);
    } else {
      setErrorCode(prevState => ({ type: FORM_SUBMISSION_ERROR, count: prevState.count + 1 }));
    }
  };

  const handleSubmit = (e) => {
    e.preventDefault();
    if (onAccountStep) {
      goToProfileStep();
    } else {
      registerUser();
    }
  };

  useEffect(() => {
    // Two-step: never auto-submit, the SSO user goes through step 2 so the profile fields get validated.
    if (autoSubmitRegForm && userPipelineDataLoaded && !twoStep) {
      registerUser();
    }
  }, [autoSubmitRegForm, userPipelineDataLoaded]); // eslint-disable-line react-hooks/exhaustive-deps

  const renderForm = () => {
    if (institutionLogin) {
      return (
        <InstitutionLogistration
          secondaryProviders={secondaryProviders}
          headingTitle={formatMessage(messages['register.institution.login.page.title'])}
        />
      );
    }
    return (
      <>
        <Helmet>
          <title>{formatMessage(messages['register.page.title'], { siteName: getConfig().SITE_NAME })}</title>
        </Helmet>
        <RedirectLogistration
          host={host}
          authenticatedUser={registrationResult.authenticatedUser}
          success={registrationResult.success}
          redirectUrl={registrationResult.redirectUrl}
          finishAuthUrl={finishAuthUrl}
          optionalFields={optionalFields}
          registrationEmbedded={registrationEmbedded}
          redirectToProgressiveProfilingPage={
            getConfig().ENABLE_PROGRESSIVE_PROFILING_ON_AUTHN && !flags.twoStepRegistration
            && !!Object.keys(optionalFields.fields).length
          }
        />
        {autoSubmitRegForm && !twoStep && !errorCode.type ? (
          <div className="mw-xs mt-5 text-center">
            <Spinner animation="border" variant="primary" id="tpa-spinner" />
          </div>
        ) : (
          <div
            className={classNames(
              'mw-xs mt-3',
              { 'w-100 m-auto pt-4 main-content': registrationEmbedded, 'tpdco-reg': twoStep },
            )}
          >
            <ThirdPartyAuthAlert
              currentProvider={currentProvider}
              platformName={platformName}
              referrer={REGISTER_PAGE}
            />
            <RegistrationFailure
              errorCode={errorCode.type}
              failureCount={errorCode.count}
              context={{ provider: currentProvider, errorMessage: thirdPartyAuthErrorMessage }}
            />
            {!errorCode.type && <EdlyLogistrationInfo />}
            <Form id="registration-form" name="registration-form">
              {flags.twoStepRegistration && <TwoStepHeader step={step} onBack={() => setStep(1)} />}
              {!(flags.twoStepRegistration && step === 2) && (
                <>
                  <NameField
                    name="name"
                    value={formFields.name}
                    shouldFetchUsernameSuggestions={!formFields.username.trim()}
                    handleChange={handleOnChange}
                    handleErrorChange={handleErrorChange}
                    errorMessage={errors.name}
                    helpText={twoStep ? [] : [formatMessage(messages['help.text.name'])]}
                    floatingLabel={formatMessage(messages[twoStep ? 'register.step.name.label' : 'registration.fullname.label'])}
                    {...twoStepProps('name')}
                  />
                  <EmailField
                    name="email"
                    value={formFields.email}
                    confirmEmailValue={configurableFormFields?.confirm_email}
                    handleErrorChange={handleErrorChange}
                    handleChange={handleOnChange}
                    readOnly={!!edlyPrefilledEmail && isNewUser}
                    errorMessage={errors.email}
                    helpText={twoStep ? [] : [formatMessage(messages['help.text.email'])]}
                    floatingLabel={formatMessage(messages[twoStep ? 'register.step.email.label' : 'registration.email.label'])}
                    {...twoStepProps('email')}
                  />
                  {!flags.autoGeneratedUsernameEnabled && (
                    <>
                      <UsernameField
                        name="username"
                        spellCheck="false"
                        value={formFields.username}
                        handleChange={handleOnChange}
                        handleErrorChange={handleErrorChange}
                        errorMessage={errors.username}
                        helpText={twoStep ? [] : [formatMessage(messages['help.text.username.1']), formatMessage(messages['help.text.username.2'])]}
                        floatingLabel={formatMessage(messages[twoStep ? 'register.step.username.label' : 'registration.username.label'])}
                        {...twoStepProps('username')}
                      />
                      {twoStep && <p className="tpdco-reg__hint">{formatMessage(messages['register.step.username.hint'])}</p>}
                    </>
                  )}
                  {!currentProvider && (
                    <>
                      <PasswordField
                        name="password"
                        value={formFields.password}
                        confirmPasswordValue={configurableFormFields?.confirm_password}
                        handleChange={handleOnChange}
                        handleErrorChange={handleErrorChange}
                        errorMessage={errors.password}
                        floatingLabel={formatMessage(messages[twoStep ? 'register.step.password.label' : 'registration.password.label'])}
                        {...twoStepProps('password')}
                      />
                      {twoStep && <PasswordStrength value={formFields.password} />}
                    </>
                  )}
                </>
              )}
              <ConfigurableRegistrationForm
                email={formFields.email}
                password={formFields.password}
                fieldErrors={errors}
                formFields={configurableFormFields}
                setFieldErrors={registrationEmbedded ? setTemporaryErrors : setErrors}
                setFormFields={setConfigurableFormFields}
                autoSubmitRegisterForm={autoSubmitRegForm}
                fieldDescriptions={flags.twoStepRegistration
                  ? { ...fieldDescriptions, ...optionalFields.fields } : fieldDescriptions}
                step={flags.twoStepRegistration ? step : null}
              />
              <StatefulButton
                id="register-user"
                name="register-user"
                type="submit"
                variant="brand"
                className="register-button mt-4 mb-4"
                state={submitState}
                labels={{
                  default: submitLabel,
                  pending: '',
                }}
                onClick={handleSubmit}
                onMouseDown={(e) => e.preventDefault()}
              />
              {twoStep && step === 2 && <TermsFooter />}
              {!registrationEmbedded && (
                <ThirdPartyAuth
                  currentProvider={currentProvider}
                  providers={providers}
                  secondaryProviders={secondaryProviders}
                  handleInstitutionLogin={handleInstitutionLogin}
                  thirdPartyAuthApiStatus={thirdPartyAuthApiStatus}
                />
              )}
            </Form>
          </div>
        )}

      </>
    );
  };

  if (tpaHint) {
    if (thirdPartyAuthApiStatus === PENDING_STATE) {
      return <Skeleton height={36} />;
    }
    const { provider, skipHintedLogin } = getTpaProvider(tpaHint, providers, secondaryProviders);
    if (skipHintedLogin) {
      window.location.href = getConfig().LMS_BASE_URL + provider.registerUrl;
      return null;
    }
    return provider ? <EnterpriseSSO provider={provider} /> : renderForm();
  }
  return (
    renderForm()
  );
};

RegistrationPage.propTypes = {
  institutionLogin: PropTypes.bool,
  // Actions
  handleInstitutionLogin: PropTypes.func,
};

RegistrationPage.defaultProps = {
  handleInstitutionLogin: null,
  institutionLogin: false,
};

export default RegistrationPage;
